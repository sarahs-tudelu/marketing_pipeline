def seed_media():
    canvas = Image.new("RGB", (720, 720), "#173d35")
    draw = ImageDraw.Draw(canvas)
    draw.rounded_rectangle((70, 70, 650, 650), radius=55, fill="#dce7d5")
    draw.rectangle((120, 180, 600, 500), fill="#7d9d89")
    draw.text((280, 330), "INTERNAL DEMO", fill="white", font_size=20)
    output = io.BytesIO()
    canvas.save(output, format="JPEG", quality=90, comment=b"Tudelu local fixture; no product depiction")
    video = io.BytesIO()
    with av.open(video, mode="w", format="mp4") as container:
        stream = container.add_stream("libx264", rate=24)
        stream.width = stream.height = 720
        stream.pix_fmt = "yuv420p"
        container.metadata["comment"] = "Tudelu synthetic local fixture; not AI generated"
        for _ in range(96):
            frame = av.VideoFrame.from_image(canvas)
            for packet in stream.encode(frame):
                container.mux(packet)
        for packet in stream.encode():
            container.mux(packet)
    return output.getvalue(), video.getvalue()


def seed(db, settings):
    bootstrap(db)
    facts = load_facts(db, settings.facts_path)
    existing = db.scalars(select(Asset).where(Asset.demo_only.is_(True))).all()
    if existing:
        return facts, existing
    image, video = seed_media()
    assets = [
        ingest(
            db,
            settings,
            data,
            name,
            rights="Internal demo only; generated by repository fixture script",
            tags={"product": "demo", "campaign": "Pipeline demonstration"},
            demo_only=True,
        )
        for data, name in [(image, "demo-card.jpg"), (video, "demo-clip.mp4")]
    ]
    db.commit()
    return facts, assets


def demo(db, settings):
    if any(settings.wants_live(p, db.get(Account, p)) for p in PLATFORMS) or settings.ai_mode != "fixture":
        raise ValueError("Demo requires empty LIVE_PLATFORMS and AI_MODE=fixture")
    facts, assets = seed(db, settings)
    existing = db.scalars(select(Post).where(Post.campaign == "Pipeline demonstration")).all()
    if existing:
        return report(db, existing)
    posts = []
    for platform in PLATFORMS:
        asset = next(
            a for a in assets if a.media["mime"].startswith("video/" if platform == "tiktok" else "image/")
        )
        post = draft(db, platform, "Pipeline demonstration", [asset.id], facts.id, product="demo")
        generate(db, settings, post)
        run_gate(db, settings, post)
        if post.status != "approved":
            raise ValueError(f"Demo gate failed for {platform}")
        schedule(db, settings, post)
        posts.append(post)
    # Deterministic virtual clock: exercise real scheduling windows without sleeping.
    for at in sorted(p.scheduled_at for p in posts):
        publish_due(db, settings, at=at)
    return report(db, posts)


def report(db, posts):
    return [
        {
            "id": p.id,
            "platform": p.platform,
            "status": p.status,
            "scheduled_at": str(p.scheduled_at),
            "dry_run": p.dry_run,
            "remote_id": p.remote_id,
            "request_count": len(
                db.scalars(select(RequestRecord).where(RequestRecord.post_id == p.id)).all()
            ),
        }
        for p in posts
    ]
